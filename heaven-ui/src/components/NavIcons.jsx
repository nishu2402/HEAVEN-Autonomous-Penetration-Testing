export function hasNavIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}

export default function NavIcon({ name, size = 24 }) {
  const body = PATHS[name];
  // Unknown key: render the literal so legacy text glyphs (+, ?, ↻) still show
  // rather than silently falling back to the wrong icon.
  if (!body) return <span aria-hidden="true">{name}</span>;
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={{ verticalAlign: "middle", flexShrink: 0 }}
    >
      {body}
    </svg>
  );
}
