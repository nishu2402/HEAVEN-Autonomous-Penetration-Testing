"""Guard the committed benchmark scorecard artifact + the `--scorecard` option.

``docs/benchmark_scorecard.json`` is the canonical, machine-readable headline the
README / CI / web can all cite from one source. It is regenerated by
``heaven benchmark --scorecard``; this test keeps the committed copy well-formed
and internally consistent (it does NOT re-run the ~20 s benchmark — the always-on
floor lives in ``tests/benchmarks/test_native_benchmark.py``).
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[1]
_SCORECARD = _ROOT / "docs" / "benchmark_scorecard.json"


def test_scorecard_artifact_is_present_and_well_formed():
    assert _SCORECARD.exists(), "committed benchmark scorecard is missing"
    card = json.loads(_SCORECARD.read_text())
    for key in ("tool", "kind", "generated_at", "target", "metrics",
                "required_detected", "required_total", "categories"):
        assert key in card, f"scorecard missing '{key}'"
    assert card["tool"] == "HEAVEN"


def test_scorecard_metrics_are_sane():
    card = json.loads(_SCORECARD.read_text())
    m = card["metrics"]
    for k in ("precision", "recall", "f1"):
        assert 0.0 <= float(m[k]) <= 1.0, f"{k} out of [0,1]"
    # Detected can never exceed the required total.
    assert 0 <= card["required_detected"] <= card["required_total"]
    assert card["required_total"] > 0
    assert len(card["categories"]) >= 5   # a genuinely multi-class surface


def test_scorecard_is_honestly_captioned():
    """The scorecard must carry the 'not a live third-party claim' caveat."""
    card = json.loads(_SCORECARD.read_text())
    assert "not a claim against any live third-party" in card["note"].lower()


def test_benchmark_cli_exposes_scorecard_option():
    pytest.importorskip("click")
    from click.testing import CliRunner

    from heaven.cli.benchmark import benchmark
    res = CliRunner().invoke(benchmark, ["--help"])
    assert res.exit_code == 0
    assert "--scorecard" in res.output
