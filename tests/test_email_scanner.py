# ── direct raw-endpoint probe (no MX lookup) ────────────────────────────────
# The open-relay lab and the orchestrator's bare-SMTP injection reach the probe
# through scan_smtp_server / scan_smtp_endpoint, which run against a host:port
# with no MX record at all. These exercise that path deterministically.
@pytest.mark.asyncio
async def test_scan_smtp_server_direct_detects_open_relay():
    server, port = await _start_fake_smtp(starttls=False, open_relay=True)
    try:
        s = EmailSecurityScanner(timeout=3.0)
        findings = await s.scan_smtp_server("127.0.0.1", port)
    finally:
        server.close()
        await server.wait_closed()
    got = _types(findings)
    assert "smtp_open_relay" in got  # detected with NO mx_enumeration finding
    assert "smtp_no_starttls" in got


@pytest.mark.asyncio
async def test_scan_smtp_endpoint_shapes_result():
    from heaven.recon.email_scanner import scan_smtp_endpoint
    server, port = await _start_fake_smtp(starttls=True, open_relay=False)
    try:
        res = await scan_smtp_endpoint("127.0.0.1", port)
    finally:
        server.close()
        await server.wait_closed()
    # A closed (non-relaying) server with STARTTLS yields no relay/starttls finding.
    types = {f["vuln_type"] for f in res["findings"]}
    assert res["total"] == len(res["findings"])
    assert "smtp_open_relay" not in types
    assert "smtp_no_starttls" not in types


