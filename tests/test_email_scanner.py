"""Tests for the email security scanner.

No live DNS or mail server is required: DNS is mocked with crafted records and
the SMTP relay / user-enumeration path is exercised against a tiny local SMTP
server bound to an ephemeral port. DKIM key-strength is verified with *real*
RSA keys generated by ``cryptography`` so the DER-decode path is genuinely
tested, not stubbed.
"""

from __future__ import annotations

import asyncio
import base64

import dns.resolver
import pytest
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.serialization import (
    Encoding,
    PublicFormat,
)

from heaven.recon.email_scanner import EmailSecurityScanner, scan_email_domains


# ── DNS mock ────────────────────────────────────────────────────────────────
class _TXT:
    def __init__(self, text: str):
        self._t = text

    def __str__(self) -> str:
        return self._t


class _MX:
    def __init__(self, preference: int, exchange: str):
        self.preference = preference
        self.exchange = exchange


def _install_dns(monkeypatch, records: dict):
    """Patch dns.resolver.resolve with a static (qname, rdtype) -> value map.

    A value that is an Exception instance is raised; a missing key raises
    NoAnswer (the "record does not exist" case the scanner treats as absent).
    """
    def _resolve(qname, rdtype, *a, **k):
        key = (str(qname).rstrip("."), rdtype)
        val = records.get(key)
        if val is None:
            raise dns.resolver.NoAnswer
        if isinstance(val, Exception):
            raise val
        return val
    monkeypatch.setattr(dns.resolver, "resolve", _resolve)


def _dkim_txt(bits: int) -> str:
    key = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    der = key.public_key().public_bytes(
        Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
    b64 = base64.b64encode(der).decode()
    return f"v=DKIM1; k=rsa; p={b64}"


# A real 512-bit RSA public key (SPKI DER, base64). cryptography refuses to
# *generate* keys below 1024 bits, but loading an existing small key (as we do
# when parsing a published DKIM record) is allowed — this is exactly that case.
_RSA_512_SPKI_B64 = (
    "MFwwDQYJKoZIhvcNAQEBBQADSwAwSAJBALxA+9XOsyrHUdPx4fWoth2s5NATzh15Fddk6L/"
    "liQNKCXy9Y86NYW7VA9hYFdizXXmv6aqILO0HB9I01ZnTzFcCAwEAAQ=="
)


def _dkim_txt_512() -> str:
    return f"v=DKIM1; k=rsa; p={_RSA_512_SPKI_B64}"


def _types(findings) -> set:
    return {f.vuln_type for f in findings}


# ── DKIM key decode (real crypto) ───────────────────────────────────────────
def test_dkim_key_bits_real_2048():
    txt = _dkim_txt(2048)
    p = txt.split("p=")[1]
    bits, algo = EmailSecurityScanner._dkim_key_bits(p)
    assert bits == 2048
    assert algo == "rsa"


def test_dkim_key_bits_garbage_returns_none():
    bits, algo = EmailSecurityScanner._dkim_key_bits("not-a-real-key")
    assert bits is None
    assert algo == ""


def test_dkim_key_bits_empty_is_revoked_selector():
    bits, algo = EmailSecurityScanner._dkim_key_bits("")
    assert bits is None


